package com.mindspark.app

import android.content.Context
import android.content.Intent
import android.net.ConnectivityManager
import android.net.NetworkCapabilities
import android.net.Uri
import android.os.BatteryManager
import android.os.Build
import android.os.Bundle
import android.os.Vibrator
import android.os.VibrationEffect
import android.view.WindowManager
import android.speech.tts.TextToSpeech
import android.graphics.pdf.PdfDocument
import android.graphics.Paint
import androidx.annotation.NonNull
import io.flutter.embedding.android.FlutterActivity
import io.flutter.embedding.engine.FlutterEngine
import io.flutter.plugin.common.MethodChannel
import java.io.File
import java.io.FileOutputStream
import java.util.Locale

class MainActivity: FlutterActivity() {
    private val HARDWARE_CHANNEL = "com.mindspark.app/hardware"
    private val KV_CHANNEL = "com.mindspark.app/kv_store"
    private val AUDIO_CHANNEL = "com.mindspark.app/audio"
    private val SECURITY_CHANNEL = "com.mindspark.app/security"
    private val DOCUMENT_CHANNEL = "com.mindspark.app/document"
    private val NETWORK_CHANNEL = "com.mindspark.app/network"
    private val FEEDBACK_CHANNEL = "com.mindspark.app/feedback"
    
    private var tts: TextToSpeech? = null

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        // Initialize Native Text-to-Speech Engine
        tts = TextToSpeech(applicationContext) { status ->
            if (status != TextToSpeech.ERROR) {
                tts?.language = Locale.US
            }
        }
    }

    override fun configureFlutterEngine(@NonNull flutterEngine: FlutterEngine) {
        super.configureFlutterEngine(flutterEngine)
        
        val messenger = flutterEngine.dartExecutor.binaryMessenger

        // 1. CORE HARDWARE CHANNEL
        MethodChannel(messenger, HARDWARE_CHANNEL).setMethodCallHandler { call, result ->
            when (call.method) {
                "getBatteryLevel" -> {
                    val batteryManager = getSystemService(Context.BATTERY_SERVICE) as BatteryManager
                    result.success(batteryManager.getIntProperty(BatteryManager.BATTERY_PROPERTY_CAPACITY))
                }
                "launchUrl" -> {
                    val url = call.argument<String>("url")
                    val intent = Intent(Intent.ACTION_VIEW, Uri.parse(url)).apply {
                        addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
                    }
                    startActivity(intent)
                    result.success(true)
                }
                else -> result.notImplemented()
            }
        }

        // 2. NATIVE STORAGE KEY-VALUE CHANNEL
        MethodChannel(messenger, KV_CHANNEL).setMethodCallHandler { call, result ->
            val prefs = getSharedPreferences("app_prefs", Context.MODE_PRIVATE)
            when (call.method) {
                "write" -> {
                    prefs.edit().putString(call.argument<String>("key"), call.argument<String>("value")).apply()
                    result.success(true)
                }
                "read" -> {
                    result.success(prefs.getString(call.argument<String>("key"), null))
                }
                else -> result.notImplemented()
            }
        }

        // 3. NATIVE AUDIO & SPEECH CHANNEL
        MethodChannel(messenger, AUDIO_CHANNEL).setMethodCallHandler { call, result ->
            if (call.method == "speak") {
                val text = call.argument<String>("text")
                tts?.speak(text, TextToSpeech.QUEUE_FLUSH, null, null)
                result.success(true)
            } else {
                result.notImplemented()
            }
        }

        // 4. SECURITY & ANTI-SCREENSHOT CHANNEL
        MethodChannel(messenger, SECURITY_CHANNEL).setMethodCallHandler { call, result ->
            when (call.method) {
                "enableSecureWindow" -> {
                    activity.window.addFlags(WindowManager.LayoutParams.FLAG_SECURE)
                    result.success(true)
                }
                "checkRoot" -> {
                    val rooted = File("/system/app/Superuser.apk").exists() || File("/system/xbin/su").exists()
                    result.success(rooted)
                }
                else -> result.notImplemented()
            }
        }

        // 5. NATIVE DOCUMENT GENERATION CHANNEL
        MethodChannel(messenger, DOCUMENT_CHANNEL).setMethodCallHandler { call, result ->
            if (call.method == "generatePdf") {
                val title = call.argument<String>("title") ?: "Document"
                val body = call.argument<String>("body") ?: ""
                
                val pdfDocument = PdfDocument()
                val pageInfo = PdfDocument.PageInfo.Builder(300, 600, 1).create()
                val page = pdfDocument.startPage(pageInfo)
                val canvas = page.canvas
                val paint = Paint()
                
                canvas.drawText(title, 20f, 40f, paint)
                canvas.drawText(body, 20f, 80f, paint)
                
                pdfDocument.finishPage(page)
                
                val file = File(context.cacheDir, "generated_output.pdf")
                pdfDocument.writeTo(FileOutputStream(file))
                pdfDocument.close()
                
                result.success(file.absolutePath)
            } else {
                result.notImplemented()
            }
        }

        // 6. CONNECTIVITY HARDWARE CHANNEL
        MethodChannel(messenger, NETWORK_CHANNEL).setMethodCallHandler { call, result ->
            if (call.method == "checkConnection") {
                val cm = getSystemService(Context.CONNECTIVITY_SERVICE) as ConnectivityManager
                val nw = cm.activeNetwork ?: return@setMethodCallHandler result.success(false)
                val actNw = cm.getNetworkCapabilities(nw) ?: return@setMethodCallHandler result.success(false)
                val connected = actNw.hasTransport(NetworkCapabilities.TRANSPORT_WIFI) || actNw.hasTransport(NetworkCapabilities.TRANSPORT_CELLULAR)
                result.success(connected)
            } else {
                result.notImplemented()
            }
        }

        // 7. FEEDBACK & SYSTEM BRIGHTNESS CHANNEL
        MethodChannel(messenger, FEEDBACK_CHANNEL).setMethodCallHandler { call, result ->
            when (call.method) {
                "vibrate" -> {
                    val vibrator = getSystemService(Context.VIBRATOR_SERVICE) as Vibrator
                    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
                        vibrator.vibrate(VibrationEffect.createOneShot(100, VibrationEffect.DEFAULT_AMPLITUDE))
                    } else {
                        @Suppress("DEPRECATION")
                        vibrator.vibrate(100)
                    }
                    result.success(true)
                }
                "setBrightness" -> {
                    val level = call.argument<Double>("level")?.toFloat() ?: 0.5f
                    val lp = activity.window.attributes
                    lp.screenBrightness = level
                    activity.window.attributes = lp
                    result.success(true)
                }
                else -> result.notImplemented()
            }
        }
    }

    override fun onDestroy() {
        if (tts != null) {
            tts?.stop()
            tts?.shutdown()
        }
        super.onDestroy()
    }
}
